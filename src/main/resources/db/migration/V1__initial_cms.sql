CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    role varchar(255) NOT NULL CHECK (role IN ('USER', 'EDITOR', 'ADMIN')),
    created_at timestamptz NOT NULL
);
CREATE TABLE tags (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL UNIQUE
);
CREATE TABLE contents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id bigint NOT NULL REFERENCES users,
    title varchar(255) NOT NULL,
    description text,
    body text,
    type varchar(255) NOT NULL CHECK (type IN ('ARTICLE','VIDEO','AUDIO','IMAGE')),
    status varchar(255) NOT NULL CHECK (status IN ('DRAFT','PUBLISHED','ARCHIVED')),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);
CREATE TABLE content_tags (
    content_id bigint NOT NULL REFERENCES contents,
    tag_id bigint NOT NULL REFERENCES tags,
    PRIMARY KEY (content_id, tag_id)
);
